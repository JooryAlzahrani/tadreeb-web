// ===========================================
// CORE LOGIC (Unified)
// ===========================================

document.addEventListener('DOMContentLoaded', () => {
    const darkModeToggle = document.getElementById('dark-mode-toggle');
    const languageToggle = document.getElementById('language-toggle');
    const body = document.body;
    const html = document.documentElement;
    const isDarkMode = localStorage.getItem('darkMode') === 'enabled';
    
    if (isDarkMode) {
        body.classList.add('dark-mode');
    }

    // --- Helper functions ---
    function updateDarkModeText(lang, isDark) {
        if (!darkModeToggle) return; 
        
        const modeTextElement = darkModeToggle.querySelector('.mode-text');
        
        if (modeTextElement) {
            const targetIsDark = !isDark;
            const content = lang === 'ar' ? ARABIC_CONTENT : ENGLISH_CONTENT;
            
            if (lang === 'ar') {
                modeTextElement.textContent = targetIsDark ? content['الوضع المظلم'] : content['الوضع الفاتح']; 
            } else {
                modeTextElement.textContent = targetIsDark ? 'Dark Mode' : 'Light Mode';
            }
        }
        darkModeToggle.setAttribute('data-mode', isDark ? 'dark' : 'light');
    }

    function setLanguage(lang) {
        const content = lang === 'ar' ? ARABIC_CONTENT : ENGLISH_CONTENT;
        const dir = lang === 'ar' ? 'rtl' : 'ltr';
        const isDark = body.classList.contains('dark-mode');

        html.lang = lang;
        html.dir = dir;
        
        // 1. Update general data-translate-key elements
        document.querySelectorAll('[data-translate-key]').forEach(el => {
            const key = el.getAttribute('data-translate-key');
            if (content[key]) {
                if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA' || el.tagName === 'SELECT') {
                    el.placeholder = content[key];
                } 
                else if (el.tagName === 'OPTION' && el.parentElement.id === 'gpaBasis') {
                    // Handled below
                }
                else {
                    el.textContent = content[key];
                }
            }
        });

        // 2. Update Filters (select options) - Internships page only
        const updateSelectOptions = (selectId, allKey, optionMap) => {
            const select = document.getElementById(selectId);
            if (!select) return;
            select.querySelector('option[value="all"]').textContent = content[allKey];
            select.querySelectorAll('option:not([value="all"])').forEach(opt => {
                if (optionMap[opt.value]) opt.textContent = optionMap[opt.value];
            });
        };

        const locationMap = {
            'Riyadh': content['option-riyadh'], 
            'Jeddah': content['option-jeddah'], 
            'Dhahran': content['option-dhahran']
        };
        const majorMap = {
            'Software Development': content['option-software'], 
            'Cybersecurity': content['option-cyber'], 
            'Machine Learning': content['option-ml'], 
            'Information Technology': content['option-it']
        };
        const statusMap = {
            'open': content['option-open'], 
            'closed': content['option-closed']
        };

        updateSelectOptions('locationFilter', 'filter-location', locationMap);
        updateSelectOptions('majorFilter', 'filter-major', majorMap);
        updateSelectOptions('statusFilter', 'filter-status', statusMap);
        
        // 3. GPA Basis Select Options
        const gpaBasisSelect = document.getElementById('gpaBasis');
        if (gpaBasisSelect) {
            gpaBasisSelect.querySelector('option[value=""]').textContent = content['option-select-basis'];
            gpaBasisSelect.querySelector('option[value="4.0"]').textContent = content['option-basis-4'];
            gpaBasisSelect.querySelector('option[value="5.0"]').textContent = content['option-basis-5'];
        }
        
        // 4. Update Header/Footer elements
        document.querySelector('.logo img').alt = lang === 'ar' ? 'شعار تدريب' : 'Tadreeb Logo';
        localStorage.setItem('language', lang);
        updateDarkModeText(lang, isDark);
    }
    
    // --- Event Listeners and Initialization ---
    
    if (languageToggle) {
        languageToggle.addEventListener('click', () => {
            const currentLang = html.lang;
            const newLang = currentLang === 'en' ? 'ar' : 'en';
            setLanguage(newLang);
        });
    }

    if (darkModeToggle) {
        darkModeToggle.addEventListener('click', () => {
            body.classList.toggle('dark-mode');
            const isDark = body.classList.contains('dark-mode');
            const currentLang = html.lang;

            if (isDark) {
                localStorage.setItem('darkMode', 'enabled');
            } else {
                localStorage.setItem('darkMode', 'disabled');
            }
            
            updateDarkModeText(currentLang, isDark);
        });
    }

    const storedLang = localStorage.getItem('language') || 'en';
    setLanguage(storedLang);


    // ===========================================
    // INTERNSHIPS PAGE SPECIFIC FUNCTIONS (UNIFIED)
    // ===========================================
    
    // Modal Functions (Only Apply Modal remains)
    window.openApplyModal = function() {
        document.getElementById("applyModal").style.display = "block";
    }

    window.closeApplyModal = function() {
        document.getElementById("applyModal").style.display = "none";
        // Optional: clear form on close
        const applicationForm = document.getElementById('applicationForm');
        if (applicationForm) applicationForm.reset();
    }
    
    // Handle "Apply Now" button clicks
    document.querySelectorAll('.btn-apply').forEach(button => {
        button.addEventListener('click', function(e) {
            openApplyModal();
        });
    });

    // Handle the Application Form submission (updated validation)
    const applicationForm = document.getElementById('applicationForm');
    if (applicationForm) {
        applicationForm.addEventListener('submit', function(e) {
            e.preventDefault();
            const lang = html.lang || 'en';
            const content = lang === 'ar' ? ARABIC_CONTENT : ENGLISH_CONTENT;
            
            // Validation Logic (Checks required fields)
            const requiredInputs = [
                'fullName', 'email', 'linkedin', 'university', 'major', 
                'studentID', 'academicLevel', 'passedHours', 'gpa', 'gpaBasis' 
            ];
            const requiredFiles = ['cvFile', 'transcriptFile'];

            let isValid = true;
            let gpaError = false;

            // Check input values
            requiredInputs.forEach(id => {
                if (!document.getElementById(id) || !document.getElementById(id).value.trim()) {
                    isValid = false;
                }
            });
            
            // Check file uploads
            requiredFiles.forEach(id => {
                if (!document.getElementById(id) || document.getElementById(id).files.length === 0) {
                    isValid = false;
                }
            });
            
            // Further Validation for GPA based on selected basis
            const gpaValue = parseFloat(document.getElementById('gpa').value);
            const gpaBasis = document.getElementById('gpaBasis').value;
            
            if (gpaBasis === '4.0' && gpaValue > 4.0) {
                 alert(content['apply-fail'] + " (GPA must be 4.0 or less)");
                 gpaError = true;
            } else if (gpaBasis === '5.0' && gpaValue > 5.0) {
                 alert(content['apply-fail'] + " (GPA must be 5.0 or less)");
                 gpaError = true;
            }

            if (isValid && !gpaError) {
                alert(content['apply-success']);
                applicationForm.reset();
                closeApplyModal();
            } else if (!gpaError) {
                alert(content['apply-fail']);
            }
        });
    }

    // Close modals on outside click
    window.onclick = function(event) {
        let applyModal = document.getElementById("applyModal");

        if (event.target == applyModal) {
            applyModal.style.display = "none";
        }
    }

    // Filter function (Internships page only)
    window.filterInternships = function() {
        const locationFilter = document.getElementById("locationFilter").value.toLowerCase();
        const majorFilter = document.getElementById("majorFilter").value.toLowerCase();
        const statusFilter = document.getElementById("statusFilter").value.toLowerCase();

        const cards = document.querySelectorAll(".internship-card");

        cards.forEach(card => {
            const location = card.dataset.location.toLowerCase();
            const major = card.dataset.major.toLowerCase();
            const status = card.dataset.status.toLowerCase();

            const matchLocation = locationFilter === "all" || location === locationFilter;
            const matchMajor = majorFilter === "all" || major === majorFilter;
            const matchStatus = statusFilter === "all" || status === statusFilter;

            if (matchLocation && matchMajor && matchStatus) {
                card.style.display = "flex"; 
            } else {
                card.style.display = "none";
            }
        });
    }
});